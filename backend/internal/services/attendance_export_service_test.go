// TestGenerateStudentDetailExportFormats tests individual student report generation across CSV, Excel, and PDF
func TestGenerateStudentDetailExportFormats(t *testing.T) {
	markedAt := time.Now().UTC()
	sampleDetail := &models.TeacherStudentAttendanceDetailResponse{
		Student: models.TeacherStudentBriefInfo{
			ID:         "stud-123",
			UserID:     "user-123",
			Name:       "John Doe",
			RollNumber: "CS105",
			Email:      "john@college.edu",
			ClassID:    "class-123",
			ClassName:  "BSc CS A",
			Department: "Computer Science",
			Semester:   4,
			Section:    "A",
		},
		Summary: models.TeacherStudentAttendanceDetailSummary{
			OverallPercentage: 80.0,
			TotalSessions:     10,
			TotalPresent:      8,
			TotalAbsent:       2,
			Status:            "REQUIREMENT_MET",
		},
		Subjects: []models.TeacherStudentAttendanceDetailSubject{
			{
				SubjectID:   "sub-1",
				SubjectName: "Computer Networks",
				SubjectCode: "CS204",
				Total:       10,
				Present:     8,
				Absent:      2,
				Percentage:  80.0,
				Status:      "REQUIREMENT_MET",
			},
		},
		History: models.TeacherStudentAttendanceDetailHistory{
			Records: []models.TeacherStudentAttendanceDetailHistoryRecord{
				{
					SessionID:   "sess-1",
					SubjectID:   "sub-1",
					SubjectName: "Computer Networks",
					SubjectCode: "CS204",
					StartedAt:   time.Now().UTC().Add(-2 * time.Hour),
					EndedAt:     time.Now().UTC().Add(-1 * time.Hour),
					Status:      "PRESENT",
					MarkedAt:    &markedAt,
				},
			},
		},
	}

	// 1. Test CSV
	var csvBuf bytes.Buffer
	if err := GenerateStudentDetailCSV(&csvBuf, sampleDetail); err != nil {
		t.Fatalf("GenerateStudentDetailCSV failed: %v", err)
	}
	if !strings.Contains(csvBuf.String(), "John Doe") || !strings.Contains(csvBuf.String(), "CS105") {
		t.Errorf("CSV missing student details")
	}

	// 2. Test Excel
	xlsxBytes, err := GenerateStudentDetailExcel(sampleDetail)
	if err != nil || len(xlsxBytes) == 0 {
		t.Fatalf("GenerateStudentDetailExcel failed: %v", err)
	}

	// 3. Test PDF
	pdfBytes, err := GenerateStudentDetailPDF(sampleDetail)
	if err != nil || len(pdfBytes) == 0 {
		t.Fatalf("GenerateStudentDetailPDF failed: %v", err)
	}
	if !strings.HasPrefix(string(pdfBytes[:8]), "%PDF-") {
		t.Errorf("student PDF does not have valid magic header")
	}
}
